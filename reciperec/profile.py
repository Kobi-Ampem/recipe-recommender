"""Describe the Food.com data before modelling it, and write docs/data.md.

uv run python -m reciperec.profile

Every number in docs/data.md comes from this script, so the README and the
defence guide can quote it without anyone counting by hand.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from reciperec.data import DATA_DIR, kcore

DOCS_DIR = Path(__file__).resolve().parent.parent / "docs"


def per_user_stats(counts: pd.Series) -> dict[str, float]:
    """Summary of how many interactions each user has."""
    q = counts.quantile([0.25, 0.5, 0.75, 0.9, 0.99])
    return {
        "mean": counts.mean(),
        "p25": q[0.25],
        "median": q[0.5],
        "p75": q[0.75],
        "p90": q[0.9],
        "p99": q[0.99],
        "max": counts.max(),
        "share with 1": (counts == 1).mean(),
    }


def describe(df: pd.DataFrame) -> dict[str, float]:
    users, items = df["user"].nunique(), df["item"].nunique()
    density = len(df) / (users * items)
    return {
        "interactions": len(df),
        "users": users,
        "recipes": items,
        "density": density,
        "sparsity": 1 - density,
    }


def table(rows: list[tuple[str, str]], header: tuple[str, str]) -> str:
    lines = [f"| {header[0]} | {header[1]} |", "|---|---:|"]
    lines += [f"| {a} | {b} |" for a, b in rows]
    return "\n".join(lines)


def main(data_dir: Path = DATA_DIR, k: int = 5) -> None:
    folder = data_dir / "foodcom"
    raw = pd.read_csv(
        folder / "RAW_interactions.csv", usecols=["user_id", "recipe_id", "date", "rating"]
    )
    raw = raw.rename(columns={"user_id": "user", "recipe_id": "item"})
    raw["date"] = pd.to_datetime(raw["date"])
    recipes = pd.read_csv(folder / "RAW_recipes.csv", usecols=["id"])

    dupes = raw.duplicated(["user", "item"]).sum()
    dedup = raw.drop_duplicates(["user", "item"], keep="first")
    core = kcore(dedup[["user", "item"]], k)
    before, after = describe(dedup), describe(core)

    ratings = raw["rating"].value_counts().sort_index()
    rated = raw[raw["rating"] > 0]
    by_year = raw["date"].dt.year.value_counts().sort_index()

    fmt_int = "{:,}".format
    sections = [
        "# Food.com data profile",
        "",
        "Generated by `uv run python -m reciperec.profile`. Do not edit by hand.",
        "",
        "## Raw files",
        "",
        table(
            [
                ("Rows in RAW_interactions.csv", fmt_int(len(raw))),
                ("Distinct users", fmt_int(raw["user"].nunique())),
                ("Distinct recipes reviewed", fmt_int(raw["item"].nunique())),
                ("Recipes in RAW_recipes.csv", fmt_int(len(recipes))),
                ("Repeat (user, recipe) pairs dropped", fmt_int(dupes)),
                ("First review", raw["date"].min().date().isoformat()),
                ("Last review", raw["date"].max().date().isoformat()),
            ],
            ("Measure", "Value"),
        ),
        "",
        "## Ratings",
        "",
        "A rating of 0 means a review left without stars.",
        "",
        table(
            [(str(r), f"{fmt_int(n)} ({n / len(raw):.1%})") for r, n in ratings.items()],
            ("Stars", "Reviews"),
        ),
        "",
        (
            f"Of reviews with stars, {(rated['rating'] == 5).mean():.1%} are 5 stars and "
            f"{(rated['rating'] >= 4).mean():.1%} are 4 or 5. The score carries little "
            'information, so the models use "reviewed this recipe" as the signal (implicit '
            "feedback)."
        ),
        "",
        "## Reviews per year",
        "",
        table([(str(y), fmt_int(n)) for y, n in by_year.items()], ("Year", "Reviews")),
        "",
        f"## Before and after the {k}-core",
        "",
        (
            f"A {k}-core keeps only users and recipes with at least {k} interactions, repeated "
            "until stable. Collaborative filtering cannot learn anything about a user or recipe "
            "seen once or twice."
        ),
        "",
        "| Measure | Deduplicated raw | " + f"{k}-core |",
        "|---|---:|---:|",
        *[
            f"| {name} | {fmt_int(before[name])} | {fmt_int(after[name])} |"
            for name in ("interactions", "users", "recipes")
        ],
        f"| Density | {before['density']:.5%} | {after['density']:.5%} |",
        f"| Sparsity | {before['sparsity']:.5%} | {after['sparsity']:.5%} |",
        "",
        (
            f"The {k}-core keeps {after['interactions'] / before['interactions']:.1%} of "
            f"interactions, {after['users'] / before['users']:.1%} of users and "
            f"{after['recipes'] / before['recipes']:.1%} of recipes."
        ),
        "",
        "## Interactions per user",
        "",
        "| Statistic | Deduplicated raw | " + f"{k}-core |",
        "|---|---:|---:|",
    ]
    raw_users = per_user_stats(dedup["user"].value_counts())
    core_users = per_user_stats(core["user"].value_counts())
    for name in raw_users:
        a, b = raw_users[name], core_users[name]
        if name == "share with 1":
            sections.append(f"| Share of users with 1 | {a:.1%} | {b:.1%} |")
        else:
            sections.append(f"| {name} | {a:,.1f} | {b:,.1f} |")
    top = core["item"].value_counts()
    top1 = top.head(max(1, int(np.ceil(len(top) * 0.01)))).sum() / len(core)
    sections += [
        "",
        f"In the {k}-core, the top 1% of recipes receive {top1:.1%} of interactions.",
        "",
    ]

    DOCS_DIR.mkdir(exist_ok=True)
    out = DOCS_DIR / "data.md"
    out.write_text("\n".join(sections))
    print("\n".join(sections))
    print(f"Saved {out.relative_to(DOCS_DIR.parent)}")


if __name__ == "__main__":
    main()
